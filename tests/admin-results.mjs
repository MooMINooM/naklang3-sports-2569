import assert from 'node:assert/strict';
import {filterResultMatches,nextUnscored,resultCards,resultState} from '../admin-results.js';
const base={sport:'football',level:'upper',type:'boys',stage:'group',group:'A',field:'F4',day:1,start:'11:15',home:'บ้านภูพระ',away:'บ้านโนนม่วง',homeScore:'',awayScore:'',published:true,ready:true};
const matches=[{...base,id:'FUB-02',start:'12:00'}, {...base,id:'FUB-01',homeScore:0,awayScore:0}, {...base,id:'FUB-10',stage:'semi',group:'',ready:false,day:3}, {...base,id:'FMG-01',sport:'football',level:'middle',type:'girls',stage:'league',group:'',published:false}, {...base,id:'VUB-01',sport:'volleyball',field:'V1',homeScore:2,awayScore:1,scoreSets:[[25,20],[20,25],[15,9]],winnerSide:'home'}];
const data={matches,fields:[{id:'F4',name:'ฟุตบอลสนามหลัก'},{id:'V1',name:'วอลเลย์บอลประถม'}],schoolLogos:{}};
const before=JSON.stringify(matches);
assert.equal(resultState(matches[1]),'completed');
assert.deepEqual(filterResultMatches(data,{status:'pending',sport:'football',level:'upper'}).map(m=>m.id),['FUB-02']);
assert.deepEqual(filterResultMatches(data,{query:'fub-02'}).map(m=>m.id),['FUB-02']);
assert.equal(filterResultMatches(data,{query:'สนามหลัก'}).length,4);
assert.equal(filterResultMatches(data,{round:'group'}).length,4);
assert.deepEqual(filterResultMatches(data,{round:'semi'}).map(m=>m.id),['FUB-10']);
assert.deepEqual(filterResultMatches(data,{published:'draft'}).map(m=>m.id),['FMG-01']);
assert.equal(JSON.stringify(matches),before);
const ordered=[{...base,id:'A',homeScore:2,awayScore:1},{...base,id:'B',ready:false},{...base,id:'C'},{...base,id:'D'}];
assert.equal(nextUnscored(ordered,'A').id,'C');
assert.equal(nextUnscored(ordered,'D').id,'C');
assert.equal(nextUnscored([ordered[0],ordered[1]],'A'),null);
const html=resultCards(matches,data);
assert(html.includes('เซต 3 <b>15–9</b>'));
assert(html.includes('data-score="FUB-10" disabled'));
assert(html.includes('ผู้ชนะ'));
const tied=resultCards([matches[2]],{...data,qualifiers:[{sport:'football',level:'upper',type:'boys',pendingTie:true}]});
assert(tied.includes('สถิติเท่ากัน'));assert(tied.includes('data-resolve-tie="FUB-10"'));
const unassigned=resultCards([{...base,id:'FMG-02',level:'middle',stage:'league',ready:false}],data);
assert(unassigned.includes('data-assign-school="FMG-02"'));
const dangerous=resultCards([{...base,id:'"><script>alert(1)</script>',home:'<img src=x onerror=alert(1)>'}],data);
assert(!dangerous.includes('<script>'));assert(!dangerous.includes('<img src=x'));
console.log('PASS: score-state filters, exact rounds, search, draft visibility, zero-score results, next unscored ordering, waiting locks, set summaries, HTML escaping');
